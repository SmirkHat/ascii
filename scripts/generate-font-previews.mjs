#!/usr/bin/env node
/**
 * Pre-render short FIGlet samples for the font picker dropdown.
 * Writes src/lib/figlet-previews.ts
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { basename, dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import figlet from 'figlet'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const CUSTOM_DIR = join(ROOT, 'src/fonts/flf')
const OUT = join(ROOT, 'src/lib/figlet-previews.ts')
const SAMPLE = 'Aa'
const MAX_LINES = 6

const stockFontsDir = join(ROOT, 'node_modules/figlet/importable-fonts')

function trimPreview(text) {
  const lines = text.replace(/\r/g, '').split('\n')
  while (lines.length && lines[0].trim() === '') lines.shift()
  while (lines.length && lines[lines.length - 1].trim() === '') lines.pop()
  return lines.slice(0, MAX_LINES).join('\n')
}

async function previewFromFlf(name, data) {
  figlet.parseFont(name, data)
  const rendered = await figlet.text(SAMPLE, {
    font: name,
    horizontalLayout: 'full',
  })
  return trimPreview(rendered)
}

async function main() {
  const previews = {}

  for (const file of readdirSync(CUSTOM_DIR).filter((f) =>
    f.endsWith('.flf'),
  )) {
    const name = basename(file, '.flf')
    try {
      previews[name] = await previewFromFlf(
        name,
        readFileSync(join(CUSTOM_DIR, file), 'utf8'),
      )
      console.log('✓', name)
    } catch (err) {
      console.warn('✗', name, err.message)
    }
  }

  // Stock FIGlet — only if importable-fonts are available
  try {
    const stock = readdirSync(stockFontsDir).filter((f) => f.endsWith('.js'))
    for (const file of stock) {
      const name = basename(file, '.js')
      if (previews[name]) continue
      try {
        const mod = await import(join(stockFontsDir, file))
        const data = mod.default
        previews[name] = await previewFromFlf(name, data)
      } catch (err) {
        // skip broken / huge fonts silently for speed logs
        if (process.env.DEBUG) console.warn('skip', name, err.message)
      }
    }
    console.log(`stock done, total ${Object.keys(previews).length}`)
  } catch (err) {
    console.warn('stock fonts skipped:', err.message)
  }

  const body = `/** Auto-generated by scripts/generate-font-previews.mjs — do not edit. */
export const FIGLET_PREVIEW_SAMPLE = ${JSON.stringify(SAMPLE)} as const

export const FIGLET_PREVIEWS: Record<string, string> = ${JSON.stringify(previews, null, 2)}

export function getFigletPreview(font: string): string | undefined {
  return FIGLET_PREVIEWS[font]
}
`

  writeFileSync(OUT, body)
  console.log(`Wrote ${Object.keys(previews).length} previews → ${OUT}`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
